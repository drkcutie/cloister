#!/bin/sh
# Print a migration that loads shared/blocklists.json into the backend catalog.
# When the shared catalog changes, add a migration with it:
#   backend/scripts/catalog-migration.sh > "backend/supabase/migrations/$(date -u +%Y%m%d%H%M%S)_builtin_blocklists.sql"
# The Postgres fixture runner checks that the database catalog equals the shared file.
set -eu
root=$(cd "$(dirname "$0")/../.." && pwd)
echo "-- Generated by backend/scripts/catalog-migration.sh from shared/blocklists.json. Don't edit."
echo "select cloister.load_catalog(\$catalog\$"
cat "$root/shared/blocklists.json"
echo "\$catalog\$::jsonb);"
